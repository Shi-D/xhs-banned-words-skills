def sync(skill_dir, wordlist_keys):
    ref = skill_dir / "references"
    scripts = skill_dir / "scripts"
    for d in (ref, scripts):
        if d.exists():
            shutil.rmtree(d)
        d.mkdir(parents=True)
    for key in wordlist_keys:
        shutil.copy2(WORDLISTS / f"{key}.txt", ref / f"{key}.txt")
    shutil.copy2(CHECKER, scripts / "xhs_check.py")


def main():
    SKILLS.mkdir(exist_ok=True)
    all_keys = sorted(p.stem for p in WORDLISTS.glob("*.txt"))
    missing = set(all_keys) - set(INDUSTRIES) - {"general"}
    if missing:
        raise SystemExit(f"wordlists 中有未在 INDUSTRIES 配置的词库：{missing}")

    for key, cfg in INDUSTRIES.items():
        skill_dir = SKILLS / f"{OVERALL}-{key}"
        sync(skill_dir, ["general", key])
        (skill_dir / "SKILL.md").write_text(industry_skill_md(key, cfg), encoding="utf-8")
        print(f"built {skill_dir.relative_to(ROOT)}")

    overall = SKILLS / OVERALL
    sync(overall, all_keys)
    if not (overall / "SKILL.md").exists():
        print(f"warning: {overall.relative_to(ROOT)}/SKILL.md 不存在（总 skill 的 SKILL.md 需手写）")
    print(f"built {overall.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
